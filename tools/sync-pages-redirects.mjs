// Keep Vercel usable for rollback while sharing the same legacy URL map.
import fs from 'node:fs';

const { redirects = [] } = JSON.parse(fs.readFileSync('vercel.json', 'utf8'));
const rules = redirects.flatMap(({ source, destination, permanent, statusCode }) => {
  if (!/^\/[\w/.:_-]*$/.test(source)) {
    throw new Error(`Unsupported redirect syntax; translate explicitly for Pages: ${source}`);
  }
  const status = statusCode ?? (permanent ? 308 : 307);
  const sources = source.endsWith('/') && source !== '/' ? [source, source.slice(0, -1)] : [source];
  return sources.map((url) => ({ url, destination, status }));
});
// Pages requires static rules before parameterized ones. Keep their relative order.
rules.sort((a, b) => Number(a.url.includes(':')) - Number(b.url.includes(':')));
const output = '# Generated by pnpm redirects:sync from vercel.json. Do not edit by hand.\n'
  + '# Include slashless legacy URLs; Pages only normalizes paths for existing assets.\n'
  + rules.map(({ url, destination, status }) => `${url} ${destination} ${status}`).join('\n') + '\n';
const target = 'public/_redirects';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) {
    console.error('Pages redirects are stale. Run pnpm redirects:sync.');
    process.exit(1);
  }
} else {
  fs.writeFileSync(target, output);
}
console.log(`Pages redirects OK: ${redirects.length} legacy rules, ${rules.length} path variants.`);
